#!/usr/bin/env python3
"""Writes bench/enums.h: enums of 8, 32 and 128 members with dense values, one of 32 with sparse
values, and their name/value tables. Run from the repository root: python3 bench/gen_enums.py"""

def members(n, step, base):
    # names alternate between a short and a longer form so lookups see two lengths
    return [("M%d" % i if i % 3 == 0 else "Member%dName" % i, base + i * step) for i in range(n)]

SETS = [("E8", 8, 1, 0), ("E32", 32, 1, 0), ("E128", 128, 1, 0), ("S32", 32, 7, 3)]

out = ["// Generated by bench/gen_enums.py; do not edit.", "#pragma once", "", "#include <string_view>", "#include <utility>", "", '#include "enum.h"', ""]
for name, n, step, base in SETS:
    ms = members(n, step, base)
    out.append("ENUM_CLASS(%s, int, %s)" % (name, ", ".join("%s = %d" % m for m in ms)))
out.append("")
for name, n, step, base in SETS:
    ms = members(n, step, base)
    out.append("inline constexpr std::pair<std::string_view, int> tab_%s[] = {%s};" % (name, ",".join('{"%s",%d}' % m for m in ms)))
out.append("")
open("bench/enums.h", "w").write("\n".join(out))
